BEGIN;
CREATE EXTENSION IF NOT EXISTS pgcrypto;
DROP SCHEMA IF EXISTS imax CASCADE;
CREATE SCHEMA imax;
SET search_path TO imax, public;

CREATE TABLE rol (
	id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nombre VARCHAR(40) NOT NULL UNIQUE,
	descripcion TEXT,
	tipos_roles VARCHAR(60)
);

CREATE TABLE usuario (
	id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nombre VARCHAR(80) NOT NULL,
	apellido1 VARCHAR(60) NOT NULL,
	apellido2 VARCHAR(60),
	correo VARCHAR(160) NOT NULL UNIQUE,
	contrasena VARCHAR(255) NOT NULL,
	id_rol INTEGER NOT NULL REFERENCES rol(id_rol)
);

CREATE TABLE peliculas (
	id_pelicula INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	titulo VARCHAR(180) NOT NULL,
	sinopsis TEXT,
	duracion INTEGER NOT NULL CHECK(duracion > 0),
	clasificacion VARCHAR(30) NOT NULL,
	genero VARCHAR(60) NOT NULL,
	estado VARCHAR(15) NOT NULL DEFAULT 'ACTIVA' CHECK (estado IN ('ACTIVA','INACTIVA')),
	cartel TEXT
);

CREATE TABLE cine (
	id_cine INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nombre VARCHAR(120) NOT NULL,
	pais VARCHAR(80) NOT NULL,
	ciudad VARCHAR(80) NOT NULL,
	direccion VARCHAR(200) NOT NULL
);
CREATE TABLE sala (
	id_sala INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_cine INTEGER NOT NULL REFERENCES cine(id_cine),
	capacidad INTEGER NOT NULL CHECK(capacidad > 0),
	estado VARCHAR(15) NOT NULL DEFAULT 'ACTIVA' CHECK(estado IN ('ACTIVA','INACTIVA')),
	UNIQUE (id_sala,id_cine)
);

CREATE TABLE asiento (
	id_asiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_sala INTEGER NOT NULL REFERENCES sala(id_sala),
	zona VARCHAR(30) NOT NULL DEFAULT 'GENERAL',
	fila VARCHAR(5) NOT NULL,
	numero INTEGER NOT NULL CHECK(numero > 0),
	UNIQUE(id_sala,fila,numero),
	UNIQUE(id_asiento,id_sala)
);

CREATE TABLE funciones (
	id_funcion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_pelicula INTEGER NOT NULL REFERENCES peliculas(id_pelicula),
	id_cine INTEGER NOT NULL REFERENCES cine(id_cine),
	id_sala INTEGER NOT NULL,
	fecha DATE NOT NULL,
	hora_inicio TIME NOT NULL,
	hora_fin TIME NOT NULL,
	precio_base NUMERIC(10,2) NOT NULL DEFAULT 3500 CHECK(precio_base >= 0),
	estado VARCHAR(15) NOT NULL DEFAULT 'ACTIVA' CHECK(estado IN ('ACTIVA','CANCELADA')),
	CHECK(hora_fin > hora_inicio),
	FOREIGN KEY(id_sala,id_cine) REFERENCES sala(id_sala,id_cine),
	UNIQUE(id_funcion,id_sala)
);

CREATE TABLE compra (
	id_compra INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_usuario INTEGER NOT NULL REFERENCES usuario(id_usuario),
	fecha_compra TIMESTAMPTZ NOT NULL DEFAULT now(),
	total NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK(total >= 0),
	estado VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE' CHECK(estado IN ('PENDIENTE','PAGADA','RECHAZADA','CANCELADA')),
	metodo_pago VARCHAR(30) CHECK(metodo_pago IN ('TARJETA_SIMULADA','EFECTIVO_SIMULADO','TRANSFERENCIA_SIMULADA'))
);

CREATE TABLE reserva_compra (
	id_reserva INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_compra INTEGER NOT NULL REFERENCES compra(id_compra),
	id_funcion INTEGER NOT NULL,
	id_asiento INTEGER NOT NULL,
	id_sala INTEGER NOT NULL,
	estado VARCHAR(15) NOT NULL DEFAULT 'BLOQUEADA' CHECK(estado IN ('BLOQUEADA','COMPRADA','EXPIRADA','LIBERADA')),
	fecha_bloqueo TIMESTAMPTZ NOT NULL DEFAULT now(),
	fecha_expiracion TIMESTAMPTZ NOT NULL DEFAULT (now() + interval '2 minutes'),
	FOREIGN KEY(id_funcion,id_sala) REFERENCES funciones(id_funcion,id_sala),
	FOREIGN KEY(id_asiento,id_sala) REFERENCES asiento(id_asiento,id_sala),
	UNIQUE(id_reserva,id_compra,id_funcion,id_asiento),
	CHECK(fecha_expiracion > fecha_bloqueo)
);

CREATE UNIQUE INDEX uq_asiento_reservado_por_funcion
	ON reserva_compra(id_funcion,id_asiento) WHERE estado IN ('BLOQUEADA','COMPRADA');

CREATE TABLE boleto (
	id_boleto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_compra INTEGER NOT NULL REFERENCES compra(id_compra),
	id_funcion INTEGER NOT NULL REFERENCES funciones(id_funcion),
	id_asiento INTEGER NOT NULL REFERENCES asiento(id_asiento),
	id_reserva INTEGER NOT NULL UNIQUE,
	fecha_emision TIMESTAMPTZ NOT NULL DEFAULT now(),
	estado VARCHAR(15) NOT NULL DEFAULT 'VIGENTE' CHECK(estado IN ('VIGENTE','USADO','ANULADO')),
	fecha_validacion TIMESTAMPTZ,
	FOREIGN KEY(id_reserva,id_compra,id_funcion,id_asiento)
	REFERENCES reserva_compra(id_reserva,id_compra,id_funcion,id_asiento)
);

CREATE UNIQUE INDEX uq_boleto_activo_por_funcion_asiento
	ON boleto(id_funcion,id_asiento) WHERE estado <> 'ANULADO';

CREATE TABLE qr (
	id_qr UUID PRIMARY KEY,
	id_boleto INTEGER NOT NULL UNIQUE REFERENCES boleto(id_boleto),
	id_usuario_revisor INTEGER REFERENCES usuario(id_usuario),
	fecha_revision TIMESTAMPTZ
);

CREATE TABLE transaccion_log (
	id_log BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_compra INTEGER REFERENCES compra(id_compra),
	fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
	evento VARCHAR(35) NOT NULL,
	monto NUMERIC(12,2),
	detalle TEXT
);
CREATE TABLE asiento_auditoria_log (
	id_log BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_reserva INTEGER REFERENCES reserva_compra(id_reserva),
	id_funcion INTEGER REFERENCES funciones(id_funcion),
	id_asiento INTEGER REFERENCES asiento(id_asiento),
	fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
	evento VARCHAR(35) NOT NULL
);
CREATE TABLE acceso_puerta_log (
	id_log BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_boleto INTEGER REFERENCES boleto(id_boleto),
	id_usuario_operador INTEGER REFERENCES usuario(id_usuario),
	fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
	puerta VARCHAR(30) NOT NULL,
	resultado VARCHAR(30) NOT NULL
);

CREATE TABLE admin_operacion_audit (
	id_log BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_usuario INTEGER NOT NULL REFERENCES usuario(id_usuario),
	id_rol INTEGER NOT NULL REFERENCES rol(id_rol),
	fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
	ip INET,
	accion VARCHAR(80) NOT NULL,
	detalle TEXT
);

CREATE INDEX idx_funciones_fecha_cine ON funciones(fecha,id_cine);
CREATE INDEX idx_asiento_sala ON asiento(id_sala);
CREATE INDEX idx_compra_usuario ON compra(id_usuario);
CREATE INDEX idx_reserva_compra ON reserva_compra(id_compra);
CREATE INDEX idx_boleto_compra ON boleto(id_compra);
CREATE INDEX idx_auditoria_fecha ON asiento_auditoria_log(fecha);

CREATE OR REPLACE FUNCTION liberar_reservas_expiradas() RETURNS INTEGER
LANGUAGE plpgsql SET search_path = imax, public AS $$
DECLARE n INTEGER;
BEGIN
	WITH liberadas AS (
		UPDATE reserva_compra SET estado='EXPIRADA'
		WHERE estado='BLOQUEADA' AND fecha_expiracion <= clock_timestamp()
		RETURNING id_reserva,id_funcion,id_asiento
	), logs AS (
		INSERT INTO asiento_auditoria_log(id_reserva,id_funcion,id_asiento,evento)
		SELECT id_reserva,id_funcion,id_asiento,'EXPIRACION' FROM liberadas
		RETURNING 1
	) SELECT count(*) INTO n FROM liberadas;
	RETURN n;
END $$;

CREATE OR REPLACE FUNCTION reservar_asiento(p_compra INTEGER,p_funcion INTEGER,p_asiento INTEGER)
RETURNS INTEGER LANGUAGE plpgsql SET search_path = imax, public AS $$
DECLARE sala_funcion INTEGER; sala_asiento INTEGER; nueva_id INTEGER;
BEGIN
	PERFORM liberar_reservas_expiradas();
	SELECT id_sala INTO sala_funcion FROM funciones WHERE id_funcion=p_funcion AND estado='ACTIVA';
	IF sala_funcion IS NULL THEN RAISE EXCEPTION 'Funcion inexistente o cancelada'; END IF;
	SELECT id_sala INTO sala_asiento FROM asiento WHERE id_asiento=p_asiento;
	IF sala_asiento IS DISTINCT FROM sala_funcion THEN
		RAISE EXCEPTION 'El asiento no pertenece a la sala de la funcion';
	END IF;
	IF NOT EXISTS(SELECT 1 FROM compra WHERE id_compra=p_compra AND estado='PENDIENTE') THEN
		RAISE EXCEPTION 'La compra no esta pendiente';
	END IF;
	INSERT INTO reserva_compra(id_compra,id_funcion,id_asiento,id_sala)
	VALUES(p_compra,p_funcion,p_asiento,sala_funcion) RETURNING id_reserva INTO nueva_id;
	INSERT INTO asiento_auditoria_log(id_reserva,id_funcion,id_asiento,evento)
	VALUES(nueva_id,p_funcion,p_asiento,'BLOQUEO');
	RETURN nueva_id;
END $$;

CREATE OR REPLACE FUNCTION confirmar_pago_simulado(p_compra INTEGER,p_aprobado BOOLEAN,p_metodo VARCHAR DEFAULT 'TARJETA_SIMULADA')
RETURNS TEXT LANGUAGE plpgsql SET search_path = imax, public AS $$
DECLARE c compra%ROWTYPE; r RECORD; monto NUMERIC(12,2); cantidad INTEGER;
BEGIN
	SELECT * INTO c FROM compra WHERE id_compra=p_compra FOR UPDATE;
	IF NOT FOUND OR c.estado <> 'PENDIENTE' THEN RAISE EXCEPTION 'Compra no pendiente'; END IF;
	PERFORM liberar_reservas_expiradas();
	SELECT count(*) INTO cantidad FROM reserva_compra WHERE id_compra=p_compra AND estado='BLOQUEADA';
	IF cantidad=0 THEN RAISE EXCEPTION 'Compra sin asientos bloqueados vigentes'; END IF;
	IF EXISTS(SELECT 1 FROM reserva_compra WHERE id_compra=p_compra AND estado <> 'BLOQUEADA') THEN
		RAISE EXCEPTION 'Hay asientos vencidos/liberados en esta compra';
	END IF;
	IF NOT p_aprobado THEN
		UPDATE reserva_compra SET estado='LIBERADA' WHERE id_compra=p_compra AND estado='BLOQUEADA';
		INSERT INTO asiento_auditoria_log(id_reserva,id_funcion,id_asiento,evento)
			SELECT id_reserva,id_funcion,id_asiento,'PAGO_RECHAZADO' FROM reserva_compra WHERE id_compra=p_compra;
		UPDATE compra SET estado='RECHAZADA',metodo_pago=p_metodo WHERE id_compra=p_compra;
		INSERT INTO transaccion_log(id_compra,evento,detalle) VALUES(p_compra,'PAGO_RECHAZADO','Pago de prueba rechazado');
		RETURN 'RECHAZADA';
	END IF;
	-- Verificar que no expiren en el instante de confirmar
	IF EXISTS(SELECT 1 FROM reserva_compra WHERE id_compra=p_compra AND fecha_expiracion<=clock_timestamp()) THEN
		RAISE EXCEPTION 'Reserva expirada';
	END IF;
	SELECT COALESCE(SUM(f.precio_base), 0) INTO monto FROM reserva_compra AS rc
	JOIN funciones AS f ON f.id_funcion = rc.id_funcion WHERE rc.id_compra = p_compra AND rc.estado = 'BLOQUEADA';
	UPDATE compra SET estado='PAGADA',total=monto,metodo_pago=p_metodo WHERE id_compra=p_compra;
	UPDATE reserva_compra SET estado='COMPRADA' WHERE id_compra=p_compra;
	INSERT INTO asiento_auditoria_log(id_reserva,id_funcion,id_asiento,evento)
		SELECT id_reserva,id_funcion,id_asiento,'COMPRA' FROM reserva_compra WHERE id_compra=p_compra;
	FOR r IN SELECT * FROM reserva_compra WHERE id_compra=p_compra LOOP
		INSERT INTO boleto(id_compra,id_funcion,id_asiento,id_reserva)
		VALUES(p_compra,r.id_funcion,r.id_asiento,r.id_reserva);
	END LOOP;
	INSERT INTO qr(id_qr,id_boleto)
	SELECT gen_random_uuid(), b.id_boleto
	FROM boleto b WHERE b.id_compra=p_compra;
	INSERT INTO transaccion_log(id_compra,evento,monto) VALUES(p_compra,'PAGO_APROBADO',monto);
	RETURN 'PAGADA';
END $$;

CREATE OR REPLACE FUNCTION validar_qr(p_codigo UUID,p_funcion INTEGER,p_operador INTEGER,p_puerta TEXT DEFAULT 'PUERTA 1')
RETURNS TEXT LANGUAGE plpgsql SET search_path = imax, public AS $$
DECLARE b boleto%ROWTYPE; f funciones%ROWTYPE; resultado TEXT;
BEGIN
	SELECT b.* INTO b FROM qr q JOIN boleto b ON b.id_boleto=q.id_boleto
	WHERE q.id_qr=p_codigo FOR UPDATE OF b;
	IF NOT FOUND THEN RETURN 'QR NO EXISTE'; END IF;
	SELECT * INTO f FROM funciones WHERE id_funcion=b.id_funcion;
	IF b.estado='USADO' THEN resultado:='ENTRADA YA UTILIZADA';
	ELSIF b.estado='ANULADO' THEN resultado:='BOLETO ANULADO';
	ELSIF b.id_funcion<>p_funcion THEN resultado:='FUNCION INCORRECTA';
	ELSIF clock_timestamp() < (f.fecha+f.hora_inicio)-interval '30 minutes'
				OR clock_timestamp() > (f.fecha+f.hora_inicio)+interval '15 minutes' THEN
				resultado:='FUERA DE HORARIO';
	ELSE
		UPDATE boleto SET estado='USADO',fecha_validacion=clock_timestamp() WHERE id_boleto=b.id_boleto;
		UPDATE qr SET id_usuario_revisor=p_operador,fecha_revision=clock_timestamp() WHERE id_qr=p_codigo;
		resultado:='ACCESO PERMITIDO';
	END IF;
	INSERT INTO acceso_puerta_log(id_boleto,id_usuario_operador,puerta,resultado)
	VALUES(b.id_boleto,p_operador,p_puerta,resultado);
	RETURN resultado;
END $$;

COMMIT;
